#!/usr/bin/env node
// Writes assets/audio/CREDITS.md from tools/audio/sources.json and checks that every audio file on disk
// has a credit entry (and every entry has a file).
// Usage: node tools/audio/build_credits.cjs
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..', '..', 'assets', 'audio');
const src = JSON.parse(fs.readFileSync(path.join(__dirname, 'sources.json'), 'utf8'));

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const onDisk = [...walk(path.join(root, 'music')), ...walk(path.join(root, 'sfx'))].filter((f) => /\.(mp3|wav|ogg|flac)$/i.test(f)).map((f) => path.relative(root, f).replace(/\\/g, '/'));
const listed = new Set(src.map((s) => s.file));
const missingCredit = onDisk.filter((f) => !listed.has(f));
const missingFile = src.filter((s) => !onDisk.includes(s.file)).map((s) => s.file);

const block = (s) => [
  `### \`${s.file}\``,
  `- **Title:** ${s.title}`,
  `- **Author:** ${s.author}`,
  `- **Source page:** ${s.sourcePage}`,
  `- **Direct download URL:** ${s.downloadUrl}`,
  `- **License:** [${s.license}](${s.licenseUrl})`,
  `- **Attribution required:** ${s.attributionRequired ? 'YES' : 'No'}`,
  `- **Attribution line:** ${s.attribution}`,
  s.note ? `- **Note:** ${s.note}` : null,
  '',
].filter((l) => l !== null).join('\n');

const sect = (title, items) => (items.length ? `## ${title}\n\n` + items.map(block).join('\n') + '\n' : '');
const cats = [...new Set(src.filter((s) => s.file.startsWith('sfx/')).map((s) => s.category))];
const required = src.filter((s) => s.attributionRequired);

const md = [
  '# Audio credits',
  '',
  'Every file under `assets/audio/music` and `assets/audio/sfx` was downloaded from the source listed below. Nothing here was synthesised or generated locally.',
  'File paths are relative to `assets/audio/`. Generated by `tools/audio/build_credits.cjs` from `tools/audio/sources.json`.',
  '',
  '## License summary',
  '',
  '| License | Free use in a social-media video | Attribution | Used for |',
  '|---|---|---|---|',
  '| [Pixabay Content License](https://pixabay.com/service/license-summary/) | Yes (commercial and non-commercial; no standalone redistribution of the file) | Not required | Pixabay music |',
  '| [Mixkit Stock Music Free License](https://mixkit.co/license/#musicFree) | Yes ("any web or social media platform"; not CDs/DVDs, TV/radio, games) | Not required | Mixkit music |',
  '| [Mixkit Sound Effects Free License](https://mixkit.co/license/#sfxFree) | Yes (commercial and non-commercial; no redistribution as stock) | Not required | Mixkit sound effects |',
  '| [CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/) | Yes (public domain dedication) | Not required | Freesound sound effects |',
  '| [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/) | Yes | **Required** (credit in the post text) | Scott Buckley |',
  '| [CC BY 3.0](https://creativecommons.org/licenses/by/3.0/) | Yes | **Required** (credit in the post text) | Broke For Free, Tours (Free Music Archive) |',
  '',
  '### Files that REQUIRE an attribution line in the post',
  '',
  ...required.map((s) => `- \`${s.file}\`: ${s.attribution}`),
  '',
  'All other files need no credit (a courtesy credit is optional).',
  '',
  sect('Music - ranked candidates', src.filter((s) => s.category === 'music')),
  sect('Music - alternates (downloaded and analysed, not in the main ranking)', src.filter((s) => s.category === 'music (alternate)')),
  ...cats.map((c) => sect('SFX - ' + c, src.filter((s) => s.file.startsWith('sfx/') && s.category === c))),
].join('\n');
fs.writeFileSync(path.join(root, 'CREDITS.md'), md);
console.log(`CREDITS.md written: ${src.length} entries, ${onDisk.length} audio files on disk`);
console.log('files without credit entry: ' + (missingCredit.length ? missingCredit.join(', ') : 'none'));
console.log('credit entries without file: ' + (missingFile.length ? missingFile.join(', ') : 'none'));
